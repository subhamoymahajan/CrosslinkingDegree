"""Compare NaCl property correlations for NC_1D and NC_2D at f=1.

Run: conda run -n tfml python plot_combined_correlations.py
Reads correlation CSVs generated by the two prediction scripts. Outputs
Pearson and Spearman figures and combined tables in combined_predictions/.
"""
import os
import tempfile
from pathlib import Path

os.environ.setdefault('MPLCONFIGDIR', str(Path(tempfile.gettempdir()) / 'dc3_mpl'))
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.colors import hsv_to_rgb
import numpy as np
import pandas as pd


METRICS = ['R', 'F', 'B']
DATASETS = [('NC_1D', 'nc_1d_predictions', ['DC3', 'DC1']),
            ('NC_2D', 'nc_2d_predictions', ['DC3', 'DC1', 'HABD'])]
COLORS = {name: hsv_to_rgb((.58, saturation, .8))
          for name, saturation in [('DC3', 1.0), ('DC1', .7), ('HABD', .4)]}
LABELS = {'DC3': r'$DC_3$ ($f=1$)', 'DC1': r'$DC_1$', 'HABD': 'HABD'}


def plot_correlations(root, output, method):
    stem = 'combined_correlations_f1' if method == 'pearson' else 'combined_spearman_correlations_f1'
    fig, axes = plt.subplots(1, 2, figsize=(6, 3), sharey=True)
    fig.subplots_adjust(left=.1, right=.98, bottom=.18, top=.85, wspace=.1)
    tables = []
    for ax, (dataset, directory, descriptors) in zip(axes, DATASETS):
        comparisons = pd.read_csv(root / directory / f'{stem}.csv')
        comparisons = comparisons.loc[(comparisons.dataset == 'NaCl')
            & np.isclose(comparisons.bond_fraction, 1)
            & (comparisons.method == method)
            & comparisons.descriptor.isin(descriptors)
            & comparisons.metric.isin(METRICS)].copy()
        data = comparisons.pivot(index='metric', columns='descriptor', values='correlation').loc[
            METRICS, descriptors]
        counts = comparisons.pivot(index='metric', columns='descriptor', values='n').loc[
            METRICS, descriptors]
        if not counts.eq(counts['DC3'], axis=0).all().all():
            raise ValueError(f'{dataset}: descriptors must use shared rows for each property.')
        comparisons.insert(0, 'source_dataset', dataset)
        tables.append(comparisons)
        x, width = np.arange(3), .75 / len(descriptors)
        for index, descriptor in enumerate(descriptors):
            offset = (index - (len(descriptors) - 1) / 2) * width
            values = data[descriptor].abs()
            bars = ax.bar(x + offset, values, width, color=COLORS[descriptor],
                          edgecolor='.2', linewidth=.6, label=LABELS[descriptor])
            for bar, value in zip(bars, values):
                ax.annotate(f'{value:.2f}', (bar.get_x() + bar.get_width()/2, value),
                            xytext=(0, 3), textcoords='offset points', ha='center', fontsize=6)
        ax.set_xticks(x, [f'{metric}\n$n={int(counts.loc[metric, "DC3"])}$' for metric in METRICS])
        ax.text(.5, .97, f'{dataset.replace("_", " ")} · NaCl',
                transform=ax.transAxes, ha='center', va='top', fontsize=9)
        ax.set_ylim(0, 1)
        ax.set_yticks(np.arange(0, 1.01, .2))
    axes[0].set_ylabel(r'$|\mathrm{Pearson}\ r|$' if method == 'pearson'
                       else r'$|\mathrm{Spearman}\ \rho|$')
    handles, labels = axes[1].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', ncol=3, frameon=False,
               fontsize=12, handlelength=2.4, handleheight=1.2)
    for ext in ['png']:
        fig.savefig(output / f'{stem}.{ext}', dpi=300)
    plt.close(fig)
    pd.concat(tables, ignore_index=True).to_csv(output / f'{stem}.csv', index=False)


def main():
    root = Path(__file__).resolve().parent / 'neural_network_cross_validation'
    output = root / 'combined_predictions'
    output.mkdir(exist_ok=True)
    with plt.rc_context({'font.size': 9, 'axes.labelsize': 12,
                         'xtick.labelsize': 11, 'ytick.labelsize': 11,
                         'axes.spines.top': False, 'axes.spines.right': False}):
        for method in ('pearson', 'spearman'):
            plot_correlations(root, output, method)
    print(f'Saved 6 × 3 inch combined figures and correlation tables to {output}')


if __name__ == '__main__':
    main()
